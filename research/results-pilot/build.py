#!/usr/bin/env python3
"""Build a reproducible, synthetic-only results-comprehension kit."""
from __future__ import annotations

import argparse
import csv
import hashlib
import io
import json
from pathlib import Path
import subprocess
import tempfile
from zipfile import ZIP_DEFLATED, ZipFile, ZipInfo

ROOT = Path(__file__).resolve().parents[2]
DOCS = ROOT / 'docs/results-pilot'
VERSION = '1.0.0'
AUTHORED_DOCS = ['README.md', 'PROTOCOL.md', 'SESSION-SCRIPT.md',
                 'OBSERVATION-GUIDE.md', 'observation-log-template.csv']
SOURCE_FILES = [
    'package.json', 'js/content.js', 'js/worlds.js', 'js/foundations.js',
    'js/engine.js', 'js/debrief-content.js', 'js/debrief.js',
    'js/interpretation-content.js', 'js/interpretation.js', 'js/debrief-view.js',
    'js/pilot-fixtures.js', 'js/pilot.js', 'results-pilot.html', 'style.css', 'pilot.css',
    'design-system.css', 'design-assessment.css', 'design-workspaces.css',
    'research/results-pilot/build.py',
    *['docs/results-pilot/' + name for name in AUTHORED_DOCS],
]
LOG_COLUMNS = 'observation_id,session_code,round,material_version,case_id,task_id,language,paraphrase_status,evidence_navigation,misunderstanding_tags,severity,observation,proposed_revision,target_ids,status,resolution,retest_result,retest_reference'.split(',')


def validate_blank_log(data: bytes) -> None:
    rows = list(csv.reader(io.StringIO(data.decode('utf-8-sig'))))
    if not rows or rows[0] != LOG_COLUMNS:
        raise ValueError('The observation template must have the documented 18-column header.')
    if any(any(cell.strip() for cell in row) for row in rows[1:]):
        raise ValueError('Refusing to package observation data: the template must be blank.')


def load_examples() -> dict:
    script = """
import {readFileSync} from 'node:fs';
import {instrument} from './js/content.js';
import {pilotCases,pilotFixtureVersion,createPilotFixture} from './js/pilot-fixtures.js';
import {createTextReport} from './js/debrief.js';
import {validateSession} from './js/engine.js';
const examples = pilotCases.map(item => {
  const f = createPilotFixture(item.id);
  const validity = validateSession(instrument, f.session);
  if (!validity.valid || !f.session.completed) throw new Error('Invalid synthetic case: '+item.id);
  return {case:f.case, report:f.report, interpretation:f.interpretation,
    answerCount:Object.keys(f.session.answers).length,
    text:createTextReport(instrument,f.session)};
});
console.log(JSON.stringify({applicationVersion:JSON.parse(readFileSync('package.json','utf8')).version,
 instrumentVersion:instrument.version,fixtureVersion:pilotFixtureVersion,examples}));
"""
    run = subprocess.run(['node', '--input-type=module', '-'], input=script,
                         cwd=ROOT, text=True, capture_output=True, check=True)
    data = json.loads(run.stdout)
    if [case['case']['id'] for case in data['examples']] != [f'RP{n:02}' for n in range(1, 7)]:
        raise ValueError('The pilot kit needs all six documented synthetic cases.')
    if any(case['answerCount'] != 49 for case in data['examples']):
        raise ValueError('A synthetic case does not contain the current 49-item route.')
    return data


def example_key(data: dict) -> str:
    lines = ['<!-- Generated by research/results-pilot/build.py; edit source fixtures instead. -->',
             '# Synthetic example key — facilitator copy', '',
             '**SYNTHETIC MATERIAL ONLY. No participant responses or findings.**', '',
             'Read this key after recording the reader’s first unaided explanation. It describes the authored cases, not a political answer the reader must agree with. The reports use the current English result wording; Vietnamese facilitation notes are unreviewed drafts.', '',
             f"Application `{data['applicationVersion']}` · assessment `{data['instrumentVersion']}` · fixture format `{data['fixtureVersion']}` · kit `{VERSION}`.", '',
             'Each case contains 49 explicit records and the same fictional setting. The text reports in the downloadable kit preserve the entire synthetic response record and end-only setting reveal. These completed examples cannot test first-use concealment.', '']
    for item in data['examples']:
        case, report, interpretation = item['case'], item['report'], item['interpretation']
        lines += [f"## {case['id']}", '', f"**Facilitator label:** {case['title']['en']}",
                  f"**Nhãn dành cho người điều phối:** {case['title']['vi']}", '',
                  f"Tasks: {', '.join(case['taskIds'])}.", '', case['purpose']['en'], '', case['purpose']['vi'], '',
                  '**What the authored case exercises:** ' + case['facilitatorNotes']['en'], '',
                  '**Điểm cần xem xét trong ví dụ:** ' + case['facilitatorNotes']['vi'], '',
                  '### Findings actually produced by the current rules', '']
        for insight in interpretation['insights']:
            lines += [f"- **{insight['title']}** — {insight['text']}",
                      f"  Supporting response IDs: {', '.join(insight['evidenceIds']) or 'coverage only'}."]
        lines += ['', '### Theme readings', '']
        for theme in interpretation['themes']:
            lines += [f"- **{theme['title']}: {theme['headline']}.** {theme['meaning']}"]
        counts = report['responseOverview']
        neutral_values = sum(row['status'] == 'value' and row['value'] == 0
                             for theme in report['themes'] for row in theme['statements'])
        lines += ['', '### Response coverage', '',
                  f"Value statements: {counts['values']['answered']} definite (including {neutral_values} neutral), {counts['values']['uncertain']} uncertain, {counts['values']['skipped']} skipped.",
                  f"Starting assumptions: {counts['foundations']['answered']} definite, {counts['foundations']['uncertain']} uncertain, {counts['foundations']['skipped']} skipped.",
                  f"Situations: {counts['scenarios']['answered']} choices, {counts['scenarios']['uncertain']} uncertain, {counts['scenarios']['unrepresented']} none of the offered choices, {counts['scenarios']['skipped']} skipped.",
                  '', f"Completed-example setting reveal: **{report['world']['name']}** — {report['world']['inspiration']}.", '']
    return '\n'.join(lines)


def synthetic_report(item: dict, fixture_version: str) -> bytes:
    prefix = ('SYNTHETIC PILOT EXAMPLE — NOT A PARTICIPANT RESPONSE\n'
              'VÍ DỤ THỬ NGHIỆM GIẢ LẬP — KHÔNG PHẢI CÂU TRẢ LỜI CỦA NGƯỜI THAM GIA\n'
              f"Example / Ví dụ: {item['case']['id']}. Fixture format / Phiên bản ví dụ: {fixture_version}.\n"
              'The following answers were authored for comprehension testing. They are not research findings or anyone’s personal assessment.\n\n')
    return (prefix + item['text']).encode('utf-8')


def build(output: Path | None = None) -> Path:
    target = output or DOCS
    if target.is_symlink():
        raise ValueError('Refusing a symlink output directory.')
    target.mkdir(parents=True, exist_ok=True)
    sources = {name: (ROOT / name).read_bytes() for name in SOURCE_FILES}
    validate_blank_log(sources['docs/results-pilot/observation-log-template.csv'])
    data = load_examples()
    key = example_key(data).encode('utf-8')
    files = {name: sources['docs/results-pilot/' + name] for name in AUTHORED_DOCS}
    files['EXAMPLES.md'] = key
    for item in data['examples']:
        files[f"reports/SYNTHETIC-{item['case']['id']}.txt"] = synthetic_report(item, data['fixtureVersion'])
    manifest = {
        'generator': 'research/results-pilot/build.py', 'kit_version': VERSION,
        'application_version': data['applicationVersion'], 'instrument_version': data['instrumentVersion'],
        'fixture_version': data['fixtureVersion'],
        'reflection_version': data['examples'][0]['report']['version'],
        'interpretation_version': data['examples'][0]['interpretation']['version'],
        'synthetic_only': True, 'human_observations': 0,
        'cases': [{'id': item['case']['id'], 'answer_count': item['answerCount'],
                   'task_ids': item['case']['taskIds']} for item in data['examples']],
        'source_sha256': {name: hashlib.sha256(value).hexdigest() for name, value in sources.items()},
        'bundle_file_sha256': {name: hashlib.sha256(value).hexdigest() for name, value in files.items()},
    }
    manifest_bytes = (json.dumps(manifest, ensure_ascii=False, indent=2) + '\n').encode('utf-8')
    files['manifest.json'] = manifest_bytes
    bundle = io.BytesIO()
    with ZipFile(bundle, 'w', compression=ZIP_DEFLATED) as archive:
        for name, payload in sorted(files.items()):
            info = ZipInfo(name, (2026, 10, 26, 0, 0, 0))
            info.compress_type = ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            archive.writestr(info, payload)
    outputs = {'EXAMPLES.md': key, 'manifest.json': manifest_bytes,
               f'results-pilot-{VERSION}.zip': bundle.getvalue()}
    for name in outputs:
        if (target / name).is_symlink():
            raise ValueError('Refusing to replace a symlink artifact: ' + name)
    with tempfile.TemporaryDirectory(prefix='.pilot-build-', dir=target) as temporary:
        for name, value in outputs.items():
            staged = Path(temporary) / name
            staged.write_bytes(value)
            staged.replace(target / name)
    return target / f'results-pilot-{VERSION}.zip'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, help='Output directory for the three generated artifacts')
    args = parser.parse_args()
    path = build(args.output)
    print(f'Built synthetic pilot kit: {path}')
