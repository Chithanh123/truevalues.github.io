#!/usr/bin/env node
/** Produce a reviewable static artifact without publishing checkout metadata. */
import {
  copyFile, lstat, mkdir, mkdtemp, readFile, readdir, realpath, rename, rm, writeFile,
} from 'node:fs/promises';
import { realpathSync } from 'node:fs';
import { tmpdir, homedir } from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const PROJECT_ROOT = realpathSync(fileURLToPath(new URL('../', import.meta.url)));
export const DEFAULT_OUTPUT = path.join(PROJECT_ROOT, 'dist');
const OWNER_MARKER = 'Generated by Political Context scripts/build-site.js. Safe to rebuild.\n';
export const SITE_FILES = Object.freeze([
  'index.html', 'instructions.html', 'quiz.html', 'results.html', 'review.html', 'style.css', 'LICENSE',
  'assets/mark.svg',
  'js/app.js', 'js/content.js', 'js/engine.js', 'js/worlds.js', 'js/review.js',
  'js/debrief-content.js', 'js/debrief.js', 'js/debrief-view.js',
  'js/interpretation-content.js', 'js/interpretation.js',
  'results-pilot.html', 'pilot.css', 'js/pilot.js', 'js/pilot-fixtures.js',
  'question-bank.html', 'question-bank.css', 'js/question-bank.js', 'data/question-catalog.json',
  'expanded.html', 'expanded.css', 'js/expanded.js', 'js/expanded-results.js', 'js/expanded-fingerprint.js',
  'js/combined-session.js', 'js/combined-extension.js',
  'docs/results-pilot/README.md', 'docs/results-pilot/PROTOCOL.md',
  'docs/results-pilot/SESSION-SCRIPT.md', 'docs/results-pilot/OBSERVATION-GUIDE.md',
  'docs/results-pilot/observation-log-template.csv', 'docs/results-pilot/EXAMPLES.md',
  'docs/results-pilot/manifest.json', 'docs/results-pilot/results-pilot-1.0.0.zip',
  'js/foundations.js',
  'js/foundation-evidence.js', 'js/review-evidence.js', 'js/review-notes.js',
  'js/translations/vi-items.js', 'js/translations/vi-worlds.js', 'js/translations/vi-foundations.js',
  'docs/RESEARCH.md', 'docs/PILOT-GUIDE.md', 'docs/review-log-template.csv',
  'docs/DESIGN-MATRIX.md', 'docs/PROGRESS.md',
  'docs/FOUNDATIONS.md',
  'docs/SOURCES.md',
]);

const within = (parent, child) => child === parent || child.startsWith(parent + path.sep);
const missing = error => error.code === 'ENOENT';

async function inspect(file) {
  try { return await lstat(file); } catch (error) { if (missing(error)) return null; throw error; }
}

async function rejectSymlinkComponents(target) {
  const parsed = path.parse(target);
  let current = parsed.root;
  for (const part of target.slice(parsed.root.length).split(path.sep).filter(Boolean)) {
    current = path.join(current, part);
    const stat = await inspect(current);
    if (!stat) return;
    if (stat.isSymbolicLink()) throw new Error(`Refusing symlink in build path: ${current}`);
  }
}

async function rejectOutputLinks(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const target = path.join(directory, entry.name);
    if (entry.isSymbolicLink()) throw new Error(`Refusing symlink in output: ${target}`);
    if (entry.isDirectory()) await rejectOutputLinks(target);
    else if (!entry.isFile()) throw new Error(`Refusing non-file output entry: ${target}`);
  }
}

async function prepareOutput(target) {
  const protectedRoots = [path.parse(target).root, tmpdir(), homedir(), '/workspace', '/home', '/etc', '/usr', '/var', '/opt'];
  if (protectedRoots.some(root => target === path.resolve(root)) || within(target, PROJECT_ROOT)) {
    throw new Error('Unsafe output: a filesystem root or checkout ancestor cannot be a build destination.');
  }
  if (within(PROJECT_ROOT, target) && target !== DEFAULT_OUTPUT) {
    throw new Error('Unsafe output: the only build destination inside the checkout is dist/.');
  }
  await rejectSymlinkComponents(target);
  const existing = await inspect(target);
  if (!existing) return false;
  if (!existing.isDirectory()) throw new Error('Unsafe output: destination exists and is not a directory.');
  await rejectOutputLinks(target);
  const marker = path.join(target, '.nojekyll');
  const markerStat = await inspect(marker);
  if (!markerStat?.isFile() || await readFile(marker, 'utf8') !== OWNER_MARKER) {
    throw new Error('Refusing to replace an existing directory not owned by this site builder.');
  }
  return true;
}

/** Build an allowlisted artifact. Custom destinations must be outside the checkout. */
export async function buildSite(outputPath = DEFAULT_OUTPUT) {
  if (typeof outputPath !== 'string' || !outputPath.trim()) throw new Error('A non-empty output path is required.');
  const output = path.resolve(outputPath);
  const existed = await prepareOutput(output);
  for (const relative of SITE_FILES) {
    const source = path.join(PROJECT_ROOT, relative);
    await rejectSymlinkComponents(source);
    const stat = await inspect(source);
    if (!stat?.isFile()) throw new Error(`Required site file is missing or not a regular file: ${relative}`);
    if (!within(PROJECT_ROOT, await realpath(source))) throw new Error(`Source escapes checkout: ${relative}`);
  }

  const parent = path.dirname(output);
  await mkdir(parent, { recursive: true });
  await rejectSymlinkComponents(parent);
  const staging = await mkdtemp(path.join(parent, '.political-context-site-'));
  let backup = null;
  let installed = false;
  try {
    for (const relative of SITE_FILES) {
      const destination = path.join(staging, relative);
      await mkdir(path.dirname(destination), { recursive: true });
      await copyFile(path.join(PROJECT_ROOT, relative), destination);
    }
    // Presence disables Jekyll; its deterministic contents identify our output.
    await writeFile(path.join(staging, '.nojekyll'), OWNER_MARKER);
    if (existed) {
      // Recheck ownership immediately before replacing generated output.
      await prepareOutput(output);
      backup = await mkdtemp(path.join(parent, '.political-context-backup-'));
      await rename(output, path.join(backup, 'site'));
    } else if (await inspect(output)) {
      throw new Error('Build destination appeared during generation; nothing was overwritten.');
    }
    await rename(staging, output);
    installed = true;
    if (backup) await rm(backup, { recursive: true, force: true });
    return { outputPath: output, files: [...SITE_FILES, '.nojekyll'].sort() };
  } catch (error) {
    if (!installed && backup && !(await inspect(output))) {
      await rename(path.join(backup, 'site'), output);
      await rm(backup, { recursive: true, force: true });
    }
    throw error;
  } finally {
    if (!installed) await rm(staging, { recursive: true, force: true });
  }
}

if (process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url) {
  try {
    if (process.argv.length > 3) throw new Error('Usage: node scripts/build-site.js [output-directory]');
    const result = await buildSite(process.argv[2]);
    console.log(`Built ${result.files.length} static files in ${result.outputPath}`);
    console.log('This creates a local deployment artifact; nothing has been published.');
  } catch (error) {
    console.error(`Site build failed: ${error.message}`);
    process.exitCode = 1;
  }
}
